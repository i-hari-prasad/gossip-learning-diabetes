"class LightweightLGLM(nn.Module):\n"
"    def __init__(self, F, H=32, W=12):\n"
"        super().__init__()\n"
"        self.conv = nn.Conv1d(F, 16, 3, padding=1)\n"
"        self.fc1  = nn.Linear(16*W, H)\n"
"        self.fc2  = nn.Linear(H, 1)\n"
